// 2. MOTOR DE INSPECCION EN MEMORIA (SPA VALIDATOR)
// ========================================================
function isQueryBlocked(rawQuery) {
  if (!rawQuery) return false;
  
  const normalized = foldDiacritics(rawQuery.toLowerCase());

  // 1. Verificacion contra el diccionario general
  const hitDictionary = INITIAL_KEYWORDS.some(kw => {
    const cleanKw = foldDiacritics(kw.trim().toLowerCase());
    return cleanKw.length > 0 && normalized.includes(cleanKw);
  });
  if (hitDictionary) return true;

  // 2. Verificacion contra variantes Leetspeak (s3xi, m0delos, etc.)
  const hitLeet = COMPILED_LEET_REGEXES.some(({ regex }) => regex.test(rawQuery));
  if (hitLeet) return true;

  return false;
}

/**
 * Intercepta cambios de ruta en YouTube y motores dinamicos
 */
function inspectNavigationUrl(urlString, tabId) {
  try {
    const url = new URL(urlString);
    
    // Inspeccion especifica de YouTube: /results?search_query=...
    if (url.hostname.includes('youtube.com') && url.pathname.startsWith('/results')) {
      const searchQuery = url.searchParams.get('search_query');
      if (searchQuery && isQueryBlocked(searchQuery)) {
        chrome.tabs.update(tabId, { url: chrome.runtime.getURL('ui/blocked.html') });
        return;
      }
    }

    // Inspeccion para Google, Bing o buscadores SPA: /search?q=...
    if (url.searchParams.has('q')) {
      const q = url.searchParams.get('q');
      if (q && isQueryBlocked(q)) {
        chrome.tabs.update(tabId, { url: chrome.runtime.getURL('ui/blocked.html') });
        return;
      }
    }
  } catch {
    // Malformed URL
  }
}

